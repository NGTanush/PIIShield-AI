"""
PII Restoration Module — Restores only validated, uncorrupted placeholders.
Zero-leakage guarantee: Ambiguous, dropped, or corrupted tokens are never guessed.
"""
import re
from typing import Dict, List, Tuple
from validation.placeholder_validator import ValidationReport, FailureCategory


class PIIRestorer:
    """Restores PII values strictly for validated placeholders."""

    def __init__(self):
        self.restoration_log: List[Dict] = []
        self.total_attempts: int = 0
        self.successful_restorations: int = 0
        self.failed_restorations: int = 0

    def restore(
        self,
        llm_response: str,
        placeholder_mapping: Dict[str, str],
        validation_report: ValidationReport
    ) -> Tuple[str, List[Dict]]:
        """
        Restore original PII for validated placeholders only.

        Args:
            llm_response: Raw text returned by the LLM.
            placeholder_mapping: Mapping of placeholder -> original PII value.
            validation_report: Validation report classifying each placeholder.

        Returns:
            Tuple of (restored_text, restoration_log).
        """
        self.restoration_log = []
        self.successful_restorations = 0
        self.failed_restorations = 0
        restored = llm_response

        # Total attempts: all evaluated placeholders
        self.total_attempts = len(validation_report.results) + validation_report.hallucinated_count

        for result in validation_report.results:
            ph = result.placeholder
            orig_val = placeholder_mapping.get(ph, "")

            if result.category == FailureCategory.CORRECT:
                # Safe replacement (use word boundaries for opaque tokens if no brackets)
                if "[" in ph:
                    pattern = re.escape(ph)
                else:
                    pattern = r'\b' + re.escape(ph) + r'\b'

                if re.search(pattern, restored):
                    restored = re.sub(pattern, orig_val, restored)
                    self.successful_restorations += 1
                    self.restoration_log.append({
                        "placeholder": ph,
                        "restored_value": orig_val,
                        "status": "RESTORED",
                        "category": "CORRECT",
                        "notes": "Validated and restored successfully."
                    })
                else:
                    self.failed_restorations += 1
                    self.restoration_log.append({
                        "placeholder": ph,
                        "restored_value": orig_val,
                        "status": "SKIPPED",
                        "category": "MISSING_FROM_TEXT",
                        "notes": "Token validated but not found at replacement time."
                    })
            else:
                self.failed_restorations += 1
                self.restoration_log.append({
                    "placeholder": ph,
                    "restored_value": orig_val,
                    "status": "UNRESTORED",
                    "category": result.category.value.upper(),
                    "notes": result.notes
                })

        # Log hallucinated placeholders
        for h_ph in validation_report.unexpected_placeholders:
            self.restoration_log.append({
                "placeholder": h_ph,
                "restored_value": "[UNKNOWN]",
                "status": "REJECTED",
                "category": "HALLUCINATED",
                "notes": "Spurious placeholder generated by LLM; no local mapping exists."
            })

        return restored, self.restoration_log

    def get_log(self) -> List[Dict]:
        """Return the restoration audit log."""
        return list(self.restoration_log)
