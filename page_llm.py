"""Page 3: LLM Processing."""
import streamlit as st
from llm.llm_processor import (
    process_with_demo, process_with_ollama, process_with_api,
    get_available_scenarios
)
from dashboard.styles import metric_card, data_panel, highlight_placeholders, status_badge


def render():
    """Render the LLM Processing page."""
    st.markdown('<h1>🤖 LLM Processing</h1>', unsafe_allow_html=True)
    st.markdown("Send masked text to an LLM and observe how placeholders are handled.")
    
    # Check prerequisite
    if not st.session_state.get("detection_done"):
        st.warning("⚠️ Please complete **PII Detection & Masking** first.")
        return
    
    masked_text = st.session_state.get("masked_text", "")
    mapping = st.session_state.get("placeholder_mapping", {})
    
    # Show masked text
    st.markdown('<div class="section-header"><h3>📤 Masked Input</h3></div>', unsafe_allow_html=True)
    highlighted = highlight_placeholders(masked_text.replace("<", "&lt;").replace(">", "&gt;"))
    st.markdown(data_panel(highlighted), unsafe_allow_html=True)
    
    st.markdown(f"*{len(mapping)} placeholder(s) in text — original PII is kept locally and not sent to the LLM.*")
    
    # ── LLM Mode Selection ────────────────────────────────
    st.markdown('<div class="section-header"><h3>⚙️ LLM Configuration</h3></div>', unsafe_allow_html=True)
    
    mode = st.radio(
        "Select LLM Mode:",
        ["🎭 Demo Mode (No API Required)", "🦙 Ollama (Local)", "🌐 External API"],
        horizontal=True
    )
    
    scenarios = get_available_scenarios()
    scenario_keys = list(scenarios.keys())
    
    if "Demo" in mode:
        st.info("**Demo Mode**: Responses are simulated locally to demonstrate various placeholder scenarios. "
                "Responses are clearly labelled as simulated.")
        
        scenario_names = [f"{scenarios[k]['name']} — {scenarios[k]['description']}" for k in scenario_keys]
        
        selected_idx = st.selectbox("Select Test Scenario:", range(len(scenario_names)),
                                     format_func=lambda i: scenario_names[i])
        selected_scenario = scenario_keys[selected_idx]
        
    elif "Ollama" in mode:
        st.info("**Ollama Mode**: Requires Ollama running locally. Connects to `http://localhost:11434`.")
        ollama_model = st.text_input("Ollama Model:", value="llama3.2")
        selected_scenario = "normal"
        
    else:
        st.info("**API Mode**: Uses OpenAI-compatible endpoints configured in environment variables (`LLM_API_KEY`).")
        selected_scenario = "normal"
    
    # ── Process ───────────────────────────────────────────
    if st.button("🚀 Process with LLM", type="primary", use_container_width=True):
        with st.spinner("Processing..."):
            if "Demo" in mode:
                response, mode_label = process_with_demo(masked_text, selected_scenario)
            elif "Ollama" in mode:
                response, mode_label = process_with_ollama(masked_text, ollama_model)
            else:
                response, mode_label = process_with_api(masked_text)
        
        # Store results
        st.session_state["llm_response"] = response
        st.session_state["llm_mode"] = mode_label
        st.session_state["llm_scenario"] = selected_scenario
        st.session_state["data_provenance"] = "real_llm" if ("ollama" in mode_label.lower() or "api" in mode_label.lower()) else "simulated"
        st.session_state["llm_done"] = True
        # Reset downstream validation state on fresh LLM response
        st.session_state["validation_done"] = False
        st.session_state.pop("validation_report", None)
        st.session_state.pop("restored_text", None)
        
        # Display
        st.markdown('<div class="section-header"><h3>📥 LLM Response</h3></div>', unsafe_allow_html=True)
        
        cols = st.columns(2)
        with cols[0]:
            badge = status_badge(mode_label, "warning" if "demo" in mode_label else "success")
            st.markdown(f"**Mode:** {badge}", unsafe_allow_html=True)
        with cols[1]:
            scenario_display = scenarios.get(selected_scenario, {}).get("name", selected_scenario) if "Demo" in mode else "N/A"
            st.markdown(f"**Scenario:** {scenario_display}")
        
        if "demo" in mode_label:
            st.warning("⚠️ This response is **simulated** for demonstration purposes. It was not generated by a real LLM.")
        
        # Show raw response with highlighted placeholders
        highlighted_response = highlight_placeholders(
            response.replace("<", "&lt;").replace(">", "&gt;")
        )
        st.markdown(data_panel(highlighted_response), unsafe_allow_html=True)
        
        st.success("✅ LLM processing complete! Proceed to **Validation & Restoration**.")
    
    elif st.session_state.get("llm_done"):
        st.info("✅ Previous LLM response available. Proceed to **Validation & Restoration** or re-process.")

